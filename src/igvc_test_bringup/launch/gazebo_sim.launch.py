"""
gazebo_sim.launch.py

Gazebo Harmonic bringup: start the IGVC course, spawn the robot, and bridge it
into ROS 2. This is the Gazebo counterpart to isaac_nav_test.launch.py, and it
is the file that turns "we have a simulator image" into "we have a robot that
drives".

Two ways to drive the robot, chosen with drive:=
  diffdrive     Stage 1, the default until 2026-10-16. Gazebo's DiffDrive,
                declared in urdf/gazebo/gazebo_sim.urdf.xacro. It does not
                exercise ros2_control, but it does exercise the description,
                physics, sensors, odometry and TF in one go.
  ros2_control  Stage 2, the default since 2026-10-16. gz_ros2_control (a binary on ROS 2 Jazzy; RQ-06 was
                decided for it on 2026-10-08) runs the real
                diff_drive_controller and joint_state_broadcaster inside
                Gazebo, loaded with controllers.yaml and then controllers_sim.yaml,
                so the sim goes through the controller the robot uses: its
                30 Hz update rate and its 0.3 s command timeout. Commands end
                on /diff_drive_controller/cmd_vel_unstamped, as on the robot,
                and a twist_stamper makes them the TwistStamped the controller
                takes. A second stamper keeps /cmd_vel (Twist) working for
                teleop and the test scripts. Odometry is the controller's own,
                /diff_drive_controller/odom, through the same gazebo_odom_shim.
                The Gazebo-side /cmd_vel and /sim/odom_body_frame bridge
                entries are dropped. Docker only: it needs ros-jazzy-twist-
                stamper, which the pixi route does not have.

The world and this launch file read the SAME track_points.json, so the course
geometry, the robot spawn pose and igvc_lane_detection's ground-truth navigator
all share one coordinate frame with no alignment step.

TOPIC NAMES ARE THE SECTION 3.7 CONTRACT, not raw Gazebo names. The bridge is
driven by config/gazebo_bridge.yaml, which maps Gazebo's /front_zed/image onto
/front_zed_camera_x/zed_node/rgb/color/rect/image and so on, so lane detection,
Nav2 and the navigator can run against Gazebo unmodified. That file is the
contract; read it before changing anything here.

One thing renaming could not fix: Gazebo's odometry frame follows the SPAWN
HEADING, while the stack assumes it carries world axes. gazebo_odom_shim
rotates it back and is the only publisher of odom -> base_link. Section 9.3 of
docs/GAZEBO_SETUP.md has the measurement.

RUN IT FROM WSL2, NOT POWERSHELL, or there will be no window. See
docs/GAZEBO_SETUP.md section 3A.

Usage
-----
    # Once per container. Both packages are install-only, so this is seconds,
    # not a real build. It IS required: the robot xacro (igvc_2027.urdf.xacro,
    # or test_robot.urdf.xacro for robot:=2026) resolves its includes with
    # $(find igvc_test_description), which needs the ament index.
    cd /root/ros2_ws
    colcon build --symlink-install \
        --base-paths src/IGVC_robot_2026/src \
        --packages-select zed_description igvc_test_description igvc_test_bringup
    source install/setup.bash

    ros2 launch igvc_test_bringup gazebo_sim.launch.py

    # Then, from a second shell in the same container
    ros2 topic pub -r 10 /cmd_vel geometry_msgs/msg/Twist \\
        "{linear: {x: 0.5}, angular: {z: 0.2}}"

Arguments
---------
    world              path to the world sdf      (default: generated IGVC course)
    track_file         path to track_points.json  (default: repo copy)
    robot              2027 | 2026                (default: 2027)
        2027   the team's Onshape model (urdf/robot_2027/, generated by
               scripts/gazebo/generate_robot_2027.py). One camera, the front
               ZED X; masses, lidar pose and GPS pose are placeholders.
        2026   urdf/robots/test_robot.urdf.xacro, the previous robot
    sim_cameras        none | front | all         (default: front)
                       all is 2026 only: robot:=2027 refuses it, because the
                       2027 robot has no left or right camera
    sim_camera_width   int                        (default: 640)
    sim_camera_height  int                        (default: 360)
    sim_camera_hz      int                        (default: 15)
    headless           true | false               (default: false)
    rviz               true | false               (default: false)
    rviz_view          demo | debug               (default: demo)
        demo   config/gazebo_demo.rviz: the robot, the navigator's search
               grid and lane path, the lidar obstacle map, a short odometry
               trail and the lane detector's overlay image. Lighter, for
               watching it drive (since 2026-10-20)
        debug  config/gazebo_sim.rviz: every display, as before 2026-10-20
               (TF, laser scan, raw camera, the lane grids, YOLOPv2 markers)
    use_sim_time       true | false               (default: true)
    robot_name         spawned entity name        (default: igvc_robot)
    spawn_{x,y,z,yaw}  override the json spawn pose
    odom_axes          world | robot              (default: world)
        world  gazebo_odom_shim rotates odometry onto the world axes (east,
               north), which the ground-truth navigation nodes need
        robot  the shim passes odometry through: its axes follow the spawn
               heading, as the real robot's wheel and visual odometry do.
               For GPS tests that must see a heading error (the simulator
               otherwise hides it); the ground-truth lane grid assumes world
               axes, so do not use it with gazebo_nav_test.launch.py.
    drive              ros2_control | diffdrive   (default: ros2_control)
        see "Two ways to drive the robot" above. ros2_control needs
        use_sim_time:=true and the packages gz_ros2_control, controller_manager,
        diff_drive_controller, joint_state_broadcaster and twist_stamper; the
        launch refuses to start without them and names the apt line.

Camera budget, measured: three 1280x720 cameras at 30 Hz deliver about 7 Hz
each. The defaults here are the ones that hold up. Pass sim_cameras:=all (with
robot:=2026; the 2027 robot has one camera) deliberately, and judge it by counting messages, not by real_time_factor -
gz-sim runs physics and rendering on separate threads, so RTF sits near 1.0
while cameras lag badly.
"""

