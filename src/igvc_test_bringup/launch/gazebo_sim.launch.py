# rviz_view:= value -> RViz config under config/. gazebo_nav_test.launch.py
# validates against the same two names before passing the value on.
RVIZ_VIEWS = {
    "demo": "gazebo_demo.rviz",
    "debug": "gazebo_sim.rviz",
}


# ── Locating files in the install tree or the source tree ────────────────────
#
# The Isaac launch files do the same dance. Prefer the installed share copy so
# the file behaves normally once built, but fall back to the bind-mounted
# source tree, which is what you get when only some packages are installed.

def _repo_root() -> str:
    env = os.environ.get("IGVC_WORKSPACE_ROOT", "")
    if env and os.path.isdir(env):
        return os.path.abspath(env)
    # launch/ -> igvc_test_bringup/ -> src/ -> repo root. realpath first,
    # because --symlink-install makes __file__ a symlink into the install tree.
    here = os.path.dirname(os.path.realpath(__file__))
    return os.path.abspath(os.path.join(here, "..", "..", ".."))


def _find(rel_from_repo: str, pkg: str, rel_from_share: str) -> str:
    """Prefer the installed share copy; fall back to the source tree."""
    try:
        cand = os.path.join(get_package_share_directory(pkg), rel_from_share)
        if os.path.exists(cand):
            return cand
    except Exception:
        pass
    return os.path.join(_repo_root(), rel_from_repo)


# ── drive:=ros2_control ──────────────────────────────────────────────────────
#
# gz_ros2_control does not depend on the controllers it runs, so a lean Gazebo
# image can have the plugin and lack all of the others, and the first symptom
# would be a spawner timing out after two minutes. Check up front instead.
ROS2_CONTROL_PACKAGES = ("gz_ros2_control", "controller_manager",
                         "diff_drive_controller", "joint_state_broadcaster",
                         "twist_stamper")

# The bridge entries only Gazebo's built-in DiffDrive needs: the Twist it reads
# and the odometry it publishes. With gz_ros2_control nothing inside Gazebo
# reads /cmd_vel or writes /sim/odom_body_frame, and dropping them makes that
# literally true: `gz topic -i -t /cmd_vel` then shows no subscriber, which is
# how a run proves the command really goes through the controller.
DIFFDRIVE_BRIDGE_TOPICS = ("/cmd_vel", "/sim/odom_body_frame")


def _require_ros2_control(use_sim_time: bool) -> None:
    if not use_sim_time:
        raise RuntimeError(
            "drive:=ros2_control needs use_sim_time:=true. gz_ros2_control "
            "forces its controller manager onto simulation time, so a false "
            "value here would split the clocks and the controller would brake "
            "every command as stale.")
    missing = []
    for pkg in ROS2_CONTROL_PACKAGES:
        try:
            get_package_share_directory(pkg)
        except Exception:                             # noqa: BLE001
            missing.append(pkg)
    if missing:
        distro = os.environ.get("ROS_DISTRO", "jazzy")
        raise RuntimeError(
            "drive:=ros2_control needs packages that are not installed: %s. "
            "Install them with: apt-get install %s  (docker/Dockerfile."
            "gazebo-jazzy lists them; the pixi environment has no twist_stamper, "
            "so this mode is Docker only)"
            % (", ".join(missing),
               " ".join("ros-%s-%s" % (distro, p.replace("_", "-"))
                        for p in missing)))


def _bridge_without(src: str, ros_topics) -> str:
    """src, a bridge config, with the entries named in ros_topics removed.

    Written to a temp file so config/gazebo_bridge.yaml itself stays the one
    contract table. The copy is regenerated on every launch and is not meant
    to be edited. Refuses to continue if any named entry is not there, because
    that means the bridge file changed shape and /cmd_vel may still be bridged.
    """
    with io.open(src, encoding="utf-8") as fh:
        entries = yaml.safe_load(fh)
    kept = [e for e in entries if e.get("ros_topic_name") not in ros_topics]
    if len(entries) - len(kept) != len(ros_topics):
        raise RuntimeError(
            "%s: expected to drop exactly the entries for %s, dropped %d of "
            "%d. Update DIFFDRIVE_BRIDGE_TOPICS in gazebo_sim.launch.py."
            % (src, ", ".join(ros_topics), len(entries) - len(kept),
               len(ros_topics)))
    out = os.path.join(tempfile.gettempdir(),
                       "igvc_gazebo_bridge_ros2_control.yaml")
    with io.open(out, "w", encoding="utf-8") as fh:
        fh.write("# Generated by gazebo_sim.launch.py (drive:=ros2_control) "
                 "from\n# %s\n# without %s. Edit the original, not this.\n"
                 % (src, ", ".join(ros_topics)))
        yaml.safe_dump(kept, fh, default_flow_style=False, sort_keys=False)
    return out


def _ros2_control_actions(spawn, use_sim_time: bool) -> list:
    """The controller spawners and the command stampers for drive:=ros2_control.

    Same shape as the gz_ros2_control demos and motor_controllers.launch.py:
    once the entity is spawned, load joint_state_broadcaster, and once that is
    done, diff_drive_controller. The controller manager exists only after the
    entity has been created inside Gazebo, so a spawner started earlier just
    waits, up to its timeout. OnProcessExit also fires when `create` FAILED, in
    which case the symptom is the first spawner timing out; judge a run by
    `ros2 control list_controllers`, not by this launch's exit code.

    EVERY node here takes use_sim_time. The stampers stamp with their own clock
    and the controller compares that stamp with simulation time against its
    0.3 s command timeout, so a wall-clock stamp reads as years old and the
    controller brakes forever.
    """
    def spawner(controller):
        return Node(
            package="controller_manager",
            executable="spawner",
            # The switch waits for controller-manager update cycles, which run
            # on simulation time; at start-up the simulator can be slow enough
            # that the spawner's 5 s default expires (seen 2026-10-16:
            # joint_state_broadcaster "Switch controller timed out").
            arguments=[controller,
                       "--controller-manager", "/controller_manager",
                       "--controller-manager-timeout", "120",
                       "--switch-timeout", "30",
                       "--service-call-timeout", "30"],
            parameters=[{"use_sim_time": use_sim_time}],
            output="screen",
        )

    jsb_spawner = spawner("joint_state_broadcaster")
    ddc_spawner = spawner("diff_drive_controller")

    # The real chain's last hop, as igvc_fused_drive.launch.py has it: Nav2's
    # collision_monitor ends on /diff_drive_controller/cmd_vel_unstamped, and a
    # twist_stamper makes it the TwistStamped the Jazzy controller takes.
    cmd_stamper = Node(
        package="twist_stamper",
        executable="twist_stamper",
        name="igvc_cmd_stamper",
        output="screen",
        parameters=[{"use_sim_time": use_sim_time, "frame_id": "base_link"}],
        remappings=[
            ("cmd_vel_in", "/diff_drive_controller/cmd_vel_unstamped"),
            ("cmd_vel_out", "/diff_drive_controller/cmd_vel"),
        ],
    )
    # /cmd_vel (Twist) is what teleop_twist_keyboard, drive_probe.py and the
    # smoke test publish, and Gazebo no longer reads it in this mode. A second
    # stamper keeps all of them working unchanged. Two publishers on one topic
    # are harmless only while one source is active at a time: if Nav2 is
    # running, do not publish /cmd_vel by hand, the same rule as today.
    compat_stamper = Node(
        package="twist_stamper",
        executable="twist_stamper",
        name="igvc_cmd_stamper_compat",
        output="screen",
        parameters=[{"use_sim_time": use_sim_time, "frame_id": "base_link"}],
        remappings=[
            ("cmd_vel_in", "/cmd_vel"),
            ("cmd_vel_out", "/diff_drive_controller/cmd_vel"),
        ],
    )
    return [
        RegisterEventHandler(OnProcessExit(
            target_action=spawn, on_exit=[jsb_spawner])),
        RegisterEventHandler(OnProcessExit(
            target_action=jsb_spawner, on_exit=[ddc_spawner])),
        cmd_stamper,
        compat_stamper,
    ]


def _setup(context, *args, **kwargs):
    def cfg(name):
        return LaunchConfiguration(name).perform(context)

    repo = _repo_root()
    world = cfg("world")
    track_file = cfg("track_file")
    robot_name = cfg("robot_name")
    headless = cfg("headless").lower() in ("true", "1", "yes")
    use_sim_time = cfg("use_sim_time").lower() in ("true", "1", "yes")
    cams = cfg("sim_cameras")
    odom_axes = cfg("odom_axes")
    if odom_axes not in ("world", "robot"):
        raise RuntimeError("odom_axes:=%s is not world or robot" % odom_axes)
    drive = cfg("drive")
    if drive not in ("diffdrive", "ros2_control"):
        raise RuntimeError("drive:=%s is not diffdrive or ros2_control" % drive)
    rviz_view = cfg("rviz_view")
    if rviz_view not in RVIZ_VIEWS:
        raise RuntimeError("rviz_view:=%s is not one of %s"
                           % (rviz_view, ", ".join(RVIZ_VIEWS)))
    use_ros2_control = drive == "ros2_control"
    if use_ros2_control:
        _require_ros2_control(use_sim_time)

    # Which robot: 2027 (default since 2026-10-15, the team's Onshape model,
    # urdf/robot_2027/) or 2026 (urdf/robots/test_robot.urdf.xacro). Both use
    # the same frame and joint names, so everything downstream is shared.
    robot = cfg("robot")
    if robot not in ("2027", "2026"):
        raise RuntimeError("robot:=%s is not 2027 or 2026" % robot)
    if robot == "2027" and cams == "all":
        raise RuntimeError(
            "sim_cameras:=all asks for left and right cameras, but the 2027 "
            "robot has only the front ZED X. Use sim_cameras:=front, or "
            "robot:=2026 for the three-camera robot.")

    # sim_cameras is dispatched by two xacro:if blocks with no else branch, so
    # any value that is not one of these three silently produces a robot with
    # ZERO cameras that launches cleanly, passes every topic-name check, and
    # fails only as "the lane detector sees nothing". Catch it here instead.
    # Verified 2026-09-17: before this guard, sim_cameras:=fron spawned a
    # cameraless robot and reported no error anywhere.
    if cams not in ("none", "front", "all"):
        raise RuntimeError(
            "sim_cameras must be one of none|front|all, got %r. "
            "An unrecognised value builds a robot with no cameras at all, "
            "which looks like a broken perception stack rather than a typo."
            % cams
        )

    # ── spawn pose: json unless explicitly overridden ────────────────────────
    sx, sy, syaw = -11.8816, 0.4516, 2.356194490192345
    if os.path.exists(track_file):
        try:
            with io.open(track_file, encoding="utf-8") as fh:
                start = json.load(fh)["robot_start_pose"]
            sx = float(start["position_m"]["x"])
            sy = float(start["position_m"]["y"])
            syaw = float(start["yaw_rad"])
        except Exception as exc:                      # noqa: BLE001
            print("gazebo_sim.launch.py: could not read spawn pose from "
                  "%s (%s); using the built-in default" % (track_file, exc))
    else:
        print("gazebo_sim.launch.py: %s not found; using the built-in "
              "default spawn pose" % track_file)

    for key, default in (("spawn_x", sx), ("spawn_y", sy), ("spawn_yaw", syaw)):
        val = cfg(key)
        if val != "":
            if key == "spawn_x":
                sx = float(val)
            elif key == "spawn_y":
                sy = float(val)
            else:
                syaw = float(val)
    sz = float(cfg("spawn_z"))

    xacro_rel = (("urdf", "robot_2027", "igvc_2027.urdf.xacro") if robot == "2027"
                 else ("urdf", "robots", "test_robot.urdf.xacro"))
    xacro_file = _find(
        os.path.join("src", "igvc_test_description", *xacro_rel),
        "igvc_test_description",
        os.path.join(*xacro_rel),
    )

    xacro_cmd = [
        "xacro ", xacro_file,
        " sim:=true",
        " sim_cameras:=", cfg("sim_cameras"),
        " sim_camera_width:=", cfg("sim_camera_width"),
        " sim_camera_height:=", cfg("sim_camera_height"),
        " sim_camera_hz:=", cfg("sim_camera_hz"),
    ]
    if use_ros2_control:
        # hardware_interface:=GazeboSimSystem is the one switch the xacro reads
        # (ros2_control_info.urdf.xacro and gazebo_sim.urdf.xacro), so the
        # launch argument cannot disagree with the description. The real
        # controllers.yaml goes first and controllers_sim.yaml over it.
        controllers_file = _find(
            os.path.join("src", "igvc_test_bringup", "config",
                         "controllers.yaml"),
            "igvc_test_bringup",
            os.path.join("config", "controllers.yaml"))
        # The 2027 robot has its own wheel geometry (controllers_sim_2027.yaml).
        sim_name = ("controllers_sim_2027.yaml" if robot == "2027"
                    else "controllers_sim.yaml")
        controllers_sim_file = _find(
            os.path.join("src", "igvc_test_bringup", "config", sim_name),
            "igvc_test_bringup",
            os.path.join("config", sim_name))
        for path in (controllers_file, controllers_sim_file):
            if not os.path.isfile(path):
                raise RuntimeError("drive:=ros2_control: %s does not exist"
                                   % path)
        xacro_cmd += [
            " hardware_interface:=GazeboSimSystem",
            " controllers_file:=", controllers_file,
            " controllers_sim_file:=", controllers_sim_file,
        ]
    robot_description = Command(xacro_cmd)

    # macOS is different in two ways, and both are handled here so that no
    # script or document has to know about them.
    #
    # 1. The gz CLI on macOS REFUSES to run the server and the GUI in one
    #    process ("you cannot run both server and gui in one terminal"), so
    #    `gz sim -r world` fails outright. There the server runs with -s and
    #    the GUI is started below as its own `gz sim -g` process.
    # 2. --headless-rendering selects EGL, which is a Linux mechanism. On
    #    macOS ogre2 renders through Metal and needs no display for sensors,
    #    so the flag is left off. NOT VERIFIED ON A MAC as of 2026-09-24:
    #    render_check.sh is the first thing the Mac checklist runs for this.
    #
    # Off macOS nothing changes: the arguments are exactly what they were.
    on_macos = platform.system() == "Darwin"
    if headless:
        gz_args = world + " -r -s" + ("" if on_macos else " --headless-rendering")
    elif on_macos:
        gz_args = world + " -r -s"
    else:
        gz_args = world + " -r"

    gz = IncludeLaunchDescription(
        PythonLaunchDescriptionSource(os.path.join(
            get_package_share_directory("ros_gz_sim"), "launch",
            "gz_sim.launch.py")),
        launch_arguments={"gz_args": gz_args}.items(),
    )

    rsp = Node(
        package="robot_state_publisher",
        executable="robot_state_publisher",
        output="screen",
        parameters=[{
            # value_type=str is required. Without it launch tries to parse the
            # URDF as YAML and dies: the description is one long XML string,
            # not a structured parameter.
            "robot_description": ParameterValue(robot_description,
                                                value_type=str),
            "use_sim_time": use_sim_time,
        }],
    )

    spawn = Node(
        package="ros_gz_sim",
        executable="create",
        output="screen",
        arguments=[
            "-topic", "robot_description",
            "-name", robot_name,
            "-x", str(sx), "-y", str(sy), "-z", str(sz),
            "-Y", str(syaw),
        ],
        parameters=[{"use_sim_time": use_sim_time}],
    )

    # ── the bridge ───────────────────────────────────────────────────────────
    #
    # One parameter_bridge driven by config/gazebo_bridge.yaml, which IS the
    # section 3.7 interface contract rather than a description of it. The YAML
    # form is what lets the ROS name differ from the Gazebo name, so the
    # simulator can publish /front_zed_camera_x/zed_node/rgb/color/rect/image
    # while Gazebo still calls it /front_zed/image, and nothing downstream has
    # to be told it is talking to Gazebo. Read that file before changing this.
    bridge_cfg = _find(
        os.path.join("src", "igvc_test_bringup", "config",
                     "gazebo_bridge.yaml"),
        "igvc_test_bringup",
        os.path.join("config", "gazebo_bridge.yaml"),
    )
    if use_ros2_control:
        bridge_cfg = _bridge_without(bridge_cfg, DIFFDRIVE_BRIDGE_TOPICS)

    # ── pacing for the camera streams ────────────────────────────────────────
    #
    # The cloud is 5.5 MB per message, the depth image 0.9 MB and the RGB image
    # 0.7 MB. Over the UDP-only Fast DDS the images set, each leaves a writer as
    # a burst that overflows a reader's socket buffer, and a best-effort reader
    # (the competition's lane_segmentation is one) then receives a fraction of
    # them. Measured: clouds 15% to 34% (2026-10-07), RGB 21% and depth 35%
    # (2026-10-08), unpaced. The profile paces only those writers; it is given
    # only to the two kinds of process that publish them, via additional_env,
    # so nothing else in the launch changes. A profile the environment already
    # names is left alone. See config/fastdds_sim_camera_pacing.xml and
    # docs/GAZEBO_SETUP.md 10.13 and 10.19.
    pacing_xml = _find(
        os.path.join("src", "igvc_test_bringup", "config",
                     "fastdds_sim_camera_pacing.xml"),
        "igvc_test_bringup",
        os.path.join("config", "fastdds_sim_camera_pacing.xml"),
    )
    pacing_env = {}
    if os.environ.get("FASTRTPS_DEFAULT_PROFILES_FILE"):
        pacing_note = ("NOT applied, FASTRTPS_DEFAULT_PROFILES_FILE is already "
                       "set (%s): the camera streams may lose frames"
                       % os.environ["FASTRTPS_DEFAULT_PROFILES_FILE"])
    elif not os.path.exists(pacing_xml):
        pacing_note = "NOT applied, %s is missing" % pacing_xml
    else:
        pacing_env = {"FASTRTPS_DEFAULT_PROFILES_FILE": pacing_xml,
                      "RMW_FASTRTPS_PUBLICATION_MODE": "AUTO"}
        pacing_note = "Fast DDS flow controller from %s" % pacing_xml

    bridge = Node(
        package="ros_gz_bridge",
        executable="parameter_bridge",
        name="igvc_gz_bridge",
        output="screen",
        additional_env=pacing_env,
        parameters=[{
            "config_file": bridge_cfg,
            "use_sim_time": use_sim_time,
        }],
    )

    # ── the odometry shim ────────────────────────────────────────────────────
    #
    # Not a nicety. Gazebo's DiffDrive starts odometry at identity, so its odom
    # axes follow the spawn heading - 134.87 deg off the world axes here -
    # while track_ground_truth_node assumes odom carries world axes and
    # gt_nav_bridge_node reads the odometry pose as a grid-frame pose with no
    # TF lookup at all. Raw Gazebo odometry puts the local costmap 135 deg away
    # from the robot with every topic still green. This node rotates it back
    # and owns odom -> base_link. See docs/GAZEBO_SETUP.md 9.3.
    #
    # With drive:=ros2_control the odometry is the controller's, which also
    # starts at identity, so its axes follow the spawn heading just the same
    # and the shim is needed just the same. Only its input topic changes. The
    # controller's own TF stays off (enable_odom_tf false), so the shim is still
    # the only publisher of odom -> base_link.
    shim_input = ({"input_topic": "/diff_drive_controller/odom"}
                  if use_ros2_control else {})
    odom_shim = Node(
        package="igvc_test_bringup",
        executable="gazebo_odom_shim",
        name="gazebo_odom_shim",
        output="screen",
        parameters=[{
            # odom_axes:=robot passes odometry through, axes along the spawn
            # heading, as on the real robot (see the docstring).
            "spawn_yaw_rad": syaw if odom_axes == "world" else 0.0,
            "use_sim_time": use_sim_time,
            **shim_input,
        }],
    )

    # ── RViz, optional ───────────────────────────────────────────────────────
    #
    # Deliberately NOT an include of rviz.launch.py. That file starts its own
    # robot_state_publisher, and two of them publishing /robot_description and
    # /tf_static against each other is a confusing mess. This runs the rviz2
    # node directly and reuses the one already started above.
    #
    # It also uses its own config. config.rviz is fixed to base_link and shows
    # only the model and TF, so a driving robot appears to stand still while
    # the world slides past. gazebo_sim.rviz is fixed to odom and adds the
    # laser, camera and odometry displays. Since 2026-10-20 that file is the
    # "debug" view (rviz_view:=debug) and the default is the lighter "demo"
    # view, gazebo_demo.rviz; each file's header says what it shows.
    actions = [gz, rsp, spawn, bridge, odom_shim]
    if use_ros2_control:
        actions += _ros2_control_actions(spawn, use_sim_time)

    # ── the point-cloud re-stamp, one per camera ─────────────────────────────
    #
    # One gz_frame_id stamps the image, depth, camera_info and cloud alike, and
    # it names the OPTICAL frame, which is right for the first three. The
    # cloud's data is in the camera's body convention, so stamped optical it
    # turns the floor into a wall. The bridge sends the cloud to a private name
    # and this node republishes it on the contract name with the body frame.
    # See gazebo_bridge.yaml (CAMERAS) and docs/GAZEBO_SETUP.md 10.13.
    cloud_cams = {"none": [], "front": ["front"],
                  "all": ["front", "left", "right"]}[cams]
    for cam in cloud_cams:
        actions.append(Node(
            package="igvc_test_bringup",
            executable="gazebo_cloud_restamp",
            name="gazebo_cloud_restamp_%s" % cam,
            output="screen",
            additional_env=pacing_env,
            parameters=[{
                "input_topic": "/sim/%s_zed/points_optical_stamp" % cam,
                "output_topic":
                    "/%s_zed_camera_x/zed_node/point_cloud/cloud_registered"
                    % cam,
                "frame_id": "%s_zed_camera_x_left_camera_frame" % cam,
                "use_sim_time": use_sim_time,
            }],
        ))

    if on_macos and not headless:
        # The GUI half of point 1 above. It connects to the server over
        # gz-transport, so it can start at the same time.
        actions.append(ExecuteProcess(cmd=["gz", "sim", "-g"], output="screen"))

    use_rviz = cfg("rviz").lower() in ("true", "1", "yes")
    if use_rviz:
        rviz_file = RVIZ_VIEWS[rviz_view]
        rviz_cfg = _find(
            os.path.join("src", "igvc_test_bringup", "config", rviz_file),
            "igvc_test_bringup",
            os.path.join("config", rviz_file),
        )
        actions.append(Node(
            package="rviz2",
            executable="rviz2",
            name="rviz2",
            output="screen",
            arguments=["-d", rviz_cfg],
            parameters=[{"use_sim_time": use_sim_time}],
        ))

    print("gazebo_sim.launch.py")
    print("  repo root : %s" % repo)
    print("  world     : %s" % world)
    print("  spawn     : x=%.4f y=%.4f z=%.2f yaw=%.6f" % (sx, sy, sz, syaw))
    print("  cameras   : %s" % cams)
    if use_ros2_control:
        print("  drive     : ros2_control (gz_ros2_control: %s, then %s)"
              % (os.path.basename(controllers_file),
                 os.path.basename(controllers_sim_file)))
    else:
        print("  drive     : diffdrive (Gazebo's built-in DiffDrive)")
    print("  bridge    : %s" % bridge_cfg)
    if odom_axes == "world":
        print("  odom shim : rotating by %.6f rad (%.2f deg)"
              % (syaw, syaw * 180.0 / 3.141592653589793))
    else:
        print("  odom shim : pass-through (odom_axes:=robot): odom axes follow "
              "the spawn heading, %.2f deg from east" % (syaw * 180.0 / 3.141592653589793))
    print("  cloud     : re-stamped to the body frame for %s"
          % (", ".join(cloud_cams) or "no camera"))
    print("  cloud DDS : %s" % pacing_note)
    print("  rviz      : %s" % (("on, %s view (%s)"
                                  % (rviz_view, RVIZ_VIEWS[rviz_view]))
                                 if use_rviz else "off"))

    return actions


def generate_launch_description():
    default_world = _find(
        os.path.join("src", "igvc_test_description", "worlds",
                     "igvc_course.sdf"),
        "igvc_test_description",
        os.path.join("worlds", "igvc_course.sdf"),
    )
    default_track = os.path.join(
        _repo_root(), "IGVC_track_generator", "track_points.json")

    # ── Gazebo mesh resolution, which is fiddlier than it looks ──────────────
    #
    # sdformat's URDF parser rewrites package:// into model://, so Gazebo looks
    # for model://zed_description/meshes/zedx.stl and needs a resource root
    # that CONTAINS a directory literally named zed_description.
    #
    # The source tree cannot provide that. The checkout is src/zed-description
    # with a HYPHEN, while the package is zed_description with an UNDERSCORE,
    # so model:// never resolves against src/. Only the install tree has the
    # directory under its real package name.
    #
    # So build the path from AMENT_PREFIX_PATH: every built package contributes
    # its <prefix>/share, which is exactly where model:// expects to look. The
    # src fallback stays for igvc_test_description, whose directory name does
    # happen to match, so partially-built workspaces still find the robot.
    share_roots = []
    for prefix in os.environ.get("AMENT_PREFIX_PATH", "").split(os.pathsep):
        if not prefix:
            continue
        share = os.path.join(prefix, "share")
        if os.path.isdir(share) and share not in share_roots:
            share_roots.append(share)
    src_root = os.path.join(_repo_root(), "src")
    if os.path.isdir(src_root):
        share_roots.append(src_root)
    existing = os.environ.get("GZ_SIM_RESOURCE_PATH", "")
    if existing:
        share_roots.append(existing)

    args = [
        DeclareLaunchArgument("world", default_value=default_world),
        DeclareLaunchArgument("track_file", default_value=default_track),
        DeclareLaunchArgument("robot", default_value="2027"),
        DeclareLaunchArgument("sim_cameras", default_value="front"),
        DeclareLaunchArgument("sim_camera_width", default_value="640"),
        DeclareLaunchArgument("sim_camera_height", default_value="360"),
        DeclareLaunchArgument("sim_camera_hz", default_value="15"),
        DeclareLaunchArgument("headless", default_value="false"),
        DeclareLaunchArgument("rviz", default_value="false"),
        DeclareLaunchArgument(
            "rviz_view", default_value="demo",
            description="With rviz:=true, which RViz config. demo (the "
                        "default): gazebo_demo.rviz, the robot, search grid, "
                        "lane path, lidar map, odometry trail and detector "
                        "overlay. debug: gazebo_sim.rviz, every display."),
        DeclareLaunchArgument("use_sim_time", default_value="true"),
        DeclareLaunchArgument("robot_name", default_value="igvc_robot"),
        DeclareLaunchArgument("spawn_x", default_value=""),
        DeclareLaunchArgument("spawn_y", default_value=""),
        DeclareLaunchArgument("spawn_z", default_value="0.25"),
        DeclareLaunchArgument("spawn_yaw", default_value=""),
        DeclareLaunchArgument(
            "odom_axes", default_value="world",
            description="world: odometry rotated onto east/north (the "
                        "default, what the ground-truth navigation needs). "
                        "robot: odometry axes along the spawn heading, as on "
                        "the real robot, for GPS heading tests."),
        DeclareLaunchArgument(
            "drive", default_value="ros2_control",
            description="diffdrive: Gazebo's built-in DiffDrive reads /cmd_vel. "
                        "ros2_control (the default since 2026-10-16, as on the "
                        "real robot): gz_ros2_control runs the "
                        "real diff_drive_controller and joint_state_broadcaster "
                        "(controllers.yaml, then controllers_sim.yaml); needs "
                        "use_sim_time:=true and the controller packages."),
    ]

    return LaunchDescription(
        [SetEnvironmentVariable("GZ_SIM_RESOURCE_PATH", os.pathsep.join(share_roots))]
        + args
        + [OpaqueFunction(function=_setup)]
    )
